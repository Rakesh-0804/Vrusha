function checkUrl(url) {
  return new Promise((resolve) => {
    try {
      const req = http.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
        resolve(res.statusCode === 200);
      });
      req.on('error', () => resolve(false));
    } catch {
      resolve(false);
    }
  });
}

async function main() {
  console.log(`Starting Catalog Build & Verification for ${products.length} products...`);
  let plantImgIdx = 0;
  let seedImgIdx = 0;
  let fixedCount = 0;

  for (let i = 0; i < products.length; i++) {
    const p = products[i];
    const ok = await checkUrl(p.image);
    if (!ok) {
      console.log(`Replacing 404 image for product: ${p.id} (${p.name})`);
      if (p.category === 'seeds') {
        p.image = verifiedSeedImages[seedImgIdx % verifiedSeedImages.length];
        seedImgIdx++;
      } else {
        p.image = verifiedPlantImages[plantImgIdx % verifiedPlantImages.length];
        plantImgIdx++;
      }
      fixedCount++;
    }
  }

  const existingDb = fs.existsSync(dataPath) ? JSON.parse(fs.readFileSync(dataPath, 'utf8')) : {};
  const catalogData = { 
    categories, 
    products, 
    users: existingDb.users || demoUsers, 
    settings: existingDb.settings || {} 
  };
  fs.writeFileSync(dataPath, JSON.stringify(catalogData, null, 2), 'utf8');

  // Also sync seed script file
  const seedScriptPath = path.join(__dirname, '..', 'backend', 'seed-mega-catalog.js');
  const seedCode = `const fs = require('fs');
const path = require('path');
const catalogData = ${JSON.stringify(catalogData, null, 2)};
const dataFilePath = path.join(__dirname, 'data.json');
fs.writeFileSync(dataFilePath, JSON.stringify(catalogData, null, 2), 'utf8');
console.log('Seed Mega Catalog updated successfully! Total products:', catalogData.products.length);
`;
  fs.writeFileSync(seedScriptPath, seedCode, 'utf8');

  console.log(`Successfully generated backend/data.json & backend/seed-mega-catalog.js! Fixed images count: ${fixedCount}. Total items: ${products.length}`);
}

main();
